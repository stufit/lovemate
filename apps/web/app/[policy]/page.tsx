export async function generateMetadata({
  params,
}: {
  params: Promise<{ policy: string }>;
}) {
  const { policy } = await params;
  return {
    title:
      policy in policies
        ? policies[policy as keyof typeof policies].title
        : "페이지 없음",
  };
}
export default async function PolicyPage({
  params,
}: {
  params: Promise<{ policy: string }>;
}) {
  const { policy } = await params;
  if (!(policy in policies)) notFound();
  const data = policies[policy as keyof typeof policies];
  return (
    <main id="main" className="policy-main">
      <div className="narrow">
        <PageIntro eyebrow="우리사이 이용 안내" title={data.title}>
          {data.intro}
        </PageIntro>
        {data.sections.map(([title, body]) => (
          <section key={title}>
            <h2>{title}</h2>
            <p>{body}</p>
          </section>
        ))}
        {policy === "privacy" && <PrivacyChoice />}
        <div className="inline-links">
          <Link href="/">홈으로 돌아가기</Link>
          <Link href="/sample">결과 미리보기</Link>
        </div>
      </div>
    </main>
  );
}
